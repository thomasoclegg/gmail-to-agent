// Renders the training clips from storyboards/ with the real extension in a throwaway headless Chrome.
// See media/README.md.
//
//   node media/record.mjs                 every video
//   node media/record.mjs hero clip-bulk  only the named ones
//   node media/record.mjs --list          the videos and their outputs
//   node media/record.mjs --steps         write media/STEPS.md (the written step lists) and stop
//   node media/record.mjs --frames-only   render frames, skip the encodes
//
// Work files (frames, the Chrome profile, a copy of the extension) go to media/.out/<video>-<time>/,
// or under MEDIA_WORK when set. Finished files go where each storyboard says, in docs/media/ and store/video/.

import fs from 'node:fs';
import path from 'node:path';
import { Director } from './lib/director.mjs';
import * as enc from './lib/encode.mjs';
import { REPO, MEDIA } from './lib/browser.mjs';
import { BOARDS } from './storyboards/index.mjs';

const args = process.argv.slice(2);
const flag = (f) => args.includes(f);
const names = args.filter((a) => !a.startsWith('--'));
const log = (...a) => console.log(...a);
const rel = (p) => path.relative(REPO, p);

const unknown = names.filter((n) => !BOARDS.some((b) => b.name === n));
if (unknown.length) {
  console.error(`Unknown video: ${unknown.join(', ')}. Known: ${BOARDS.map((b) => b.name).join(', ')}`);
  process.exit(2);
}
const chosen = names.length ? BOARDS.filter((b) => names.includes(b.name)) : BOARDS;

if (flag('--list')) {
  for (const b of BOARDS) log(`${b.name.padEnd(20)} ${(b.duration / 1000).toFixed(1).padStart(5)} s  ${b.size.w * b.size.dsf}x${b.size.h * b.size.dsf}  ${b.outputs.map((o) => o.path).join(', ')}`);
  process.exit(0);
}

// ---- The written step lists (a text alternative for each silent video) ----

function writeSteps() {
  const out = path.join(MEDIA, 'STEPS.md');
  const parts = [
    '# Step lists for the videos',
    '',
    'Generated by `node media/record.mjs --steps` from the storyboards in `media/storyboards/`. Put each list next to its video: the videos are silent, and this is their text alternative.',
    '',
  ];
  for (const b of BOARDS.filter((x) => x.steps.length)) {
    parts.push(`## ${b.title}`, '', `\`${b.outputs.filter((o) => o.kind !== 'poster').map((o) => o.path).join('`, `')}\`, ${(b.duration / 1000).toFixed(0)} s`, '');
    b.steps.forEach((s, i) => parts.push(`${i + 1}. ${s}`));
    parts.push('');
  }
  fs.writeFileSync(out, parts.join('\n'));
  log(`wrote ${rel(out)}`);
}
writeSteps();
if (flag('--steps')) process.exit(0);

// ---- Render ----

let ff = null;
if (!flag('--frames-only')) {
  try {
    ff = enc.findFfmpeg();
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
}
if (ff) log(`ffmpeg: ${ff.bin} (${ff.version})`);
const workRoot = process.env.MEDIA_WORK ? path.resolve(process.env.MEDIA_WORK) : path.join(MEDIA, '.out');
const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..*/, '').replace('T', '-');
const summary = [];
let failed = false;

for (const board of chosen) {
  const work = path.join(workRoot, `${board.name}-${stamp}`);
  fs.mkdirSync(work, { recursive: true });
  log(`\n== ${board.name}: ${board.title} (${(board.duration / 1000).toFixed(1)} s) -> ${rel(work) || work}`);
  const d = new Director(board, { work, log: (...a) => log('  ', ...a) });
  const started = Date.now();
  let result;
  try {
    await d.start();
    await board.run(d);
    await d.at(board.duration);
  } catch (e) {
    failed = true;
    log(`  FAIL ${e.stack || e.message}`);
  } finally {
    result = await d.finish();
  }
  const real = ((Date.now() - started) / 1000).toFixed(0);
  log(`   ${result.frames} frames (${result.duration.toFixed(2)} s of video) in ${real} s; ${result.copies ?? '?'} copies, ${result.printViews} print views, extension ${result.version}`);
  const expected = Math.round((board.duration / 1000) * board.fps);
  fs.writeFileSync(path.join(work, 'report.json'), JSON.stringify({ board: board.name, result, captions: d.captions, marks: d.marks }, null, 2));
  if (result.frames !== expected) {
    failed = true;
    log(`  FAIL ${result.frames} frames, expected ${expected}`);
    continue;
  }
  if (result.blocked.length) log(`   blocked ${result.blocked.length} request(s) to other hosts: ${[...new Set(result.blocked.map((u) => new URL(u).host))].join(', ')}`);
  if (result.exceptions.length) log(`   page errors: ${result.exceptions.join(' | ').slice(0, 400)}`);
  // In a loop, the last caption carries on into the first.
  let caps = d.captions;
  if (board.loop && caps.length > 1 && caps.at(-1).text === caps[0].text) {
    const last = caps.at(-1);
    caps = [{ ...caps[0], end: caps[0].end + (last.end - last.start) }, ...caps.slice(1, -1)];
  }
  const problems = enc.checkCaptions(caps);
  for (const p of problems) log(`   caption: ${p}`);
  if (!ff) continue;

  for (const o of board.outputs) {
    const out = path.join(REPO, o.path);
    const opts = { fps: board.fps, ...o };
    if (o.kind === 'mp4') enc.mp4(ff, d.frames, out, opts);
    if (o.kind === 'webm') enc.webm(ff, d.frames, out, opts);
    if (o.kind === 'gif') enc.gif(ff, d.frames, out, opts);
    if (o.kind === 'srt') enc.srt(d.captions, out);
    if (o.kind === 'poster') {
      const n = d.marks[o.mark] ?? 0;
      enc.still(ff, path.join(d.frames, `f${String(n).padStart(5, '0')}.png`), out, { scale: o.scale });
    }
    const size = fs.statSync(out).size;
    const secs = ['mp4', 'webm', 'gif'].includes(o.kind) ? enc.duration(ff, out) : null;
    summary.push({ file: o.path, size, secs });
    log(`   ${o.path.padEnd(44)} ${(size / 1024).toFixed(0).padStart(6)} KB${secs ? `  ${secs.toFixed(2)} s` : ''}`);
  }
}

if (summary.length) {
  log('\nFiles:');
  for (const s of summary) log(`  ${s.file.padEnd(44)} ${(s.size / 1024).toFixed(0).padStart(6)} KB${s.secs ? `  ${s.secs.toFixed(2)} s` : ''}`);
}
process.exitCode = failed ? 1 : 0;
